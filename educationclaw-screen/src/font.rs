/// Bitmap rows of 5 bits each, bit 4 = leftmost pixel.
type Glyph = [u8; GLYPH_H as usize];

fn table() -> &'static [Glyph; 95] {
    static TABLE: OnceLock<[Glyph; 95]> = OnceLock::new();
    TABLE.get_or_init(|| {
        let mut out = [[0u8; GLYPH_H as usize]; 95];
        for (g, art) in out.iter_mut().zip(ART.iter()) {
            for (row, line) in g.iter_mut().zip(art.iter()) {
                let mut bits = 0u8;
                for (x, ch) in line.chars().take(GLYPH_W as usize).enumerate() {
                    if ch == '#' {
                        bits |= 1 << (GLYPH_W as usize - 1 - x);
                    }
                }
                *row = bits;
            }
        }
        out
    })
}

/// Is pixel (`x`, `y`) of `c` lit? Unprintable characters fall back to `?`.
pub fn pixel(c: char, x: u16, y: u16) -> bool {
    if x >= GLYPH_W || y >= GLYPH_H {
        return false;
    }
    let t = table();
    let g = match c as u32 {
        0x20..=0x7E => &t[c as usize - 0x20],
        _ => &t['?' as usize - 0x20],
    };
    g[y as usize] & (1 << (GLYPH_W - 1 - x)) != 0
}
