//! A 5x7 pixel font, authored as ASCII art so every glyph is readable in source.
//!
//! Glyphs are drawn with half-block characters, so the 7 pixel rows of a line
//! collapse into 4 terminal rows.

use std::sync::OnceLock;

pub const GLYPH_W: u16 = 5;
pub const GLYPH_H: u16 = 7;

// Glyphs are drawn at an integer scale. One font pixel becomes `scale` columns
// wide and `scale` half-rows tall, which keeps the aspect ratio right because a
// terminal cell is roughly twice as tall as it is wide.

/// Columns one glyph occupies at `scale`.
pub fn glyph_cols(scale: u16) -> u16 {
    GLYPH_W * scale
}

/// Terminal rows one line of text occupies at `scale`.
pub fn cell_rows(scale: u16) -> u16 {
    (GLYPH_H * scale).div_ceil(2)
}

/// Columns from one glyph's left edge to the next, including tracking.
pub fn advance(scale: u16) -> u16 {
    GLYPH_W * scale + scale
}

/// Width in terminal cells of `n` glyphs set side by side at `scale`.
pub fn text_width(n: usize, scale: u16) -> u16 {
    if n == 0 {
        0
    } else {
        n as u16 * advance(scale) - scale
    }
}

